  if (['china', 'taiwan', 'singapore'].includes(c)) return 'east_asian_chinese';
  if (c === 'japan') return 'east_asian_japanese';
  if (['south-korea', 'north-korea'].includes(c)) return 'east_asian_korean';
  if (c === 'vietnam') return 'southeast_asian_viet';
  if (['indonesia', 'malaysia', 'brunei', 'east-timor'].includes(c)) return 'southeast_asian_malay';
  if (c === 'philippines') return 'southeast_asian_filipino';
  if (['russia', 'ukraine', 'belarus'].includes(c)) return 'slavic_east';
  if (['poland', 'czechia', 'czech-republic', 'slovakia', 'bulgaria', 'serbia', 'croatia', 'bosnia-and-herzegovina', 'north-macedonia', 'montenegro', 'slovenia'].includes(c)) return 'slavic_west_south';
